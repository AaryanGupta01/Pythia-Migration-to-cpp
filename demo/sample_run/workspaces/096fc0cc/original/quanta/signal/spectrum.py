"""Discrete Fourier analysis without a math library: series-expansion trigonometry and a direct DFT."""


def sin_series(x: float) -> float:
    """sin(x) from its Taylor series after reducing x into [-pi, pi]."""
    two_pi: float = 6.283185307179586
    while x > 3.141592653589793:
        x -= two_pi
    while x < -3.141592653589793:
        x += two_pi
    term: float = x
    total: float = x
    for k in range(1, 14):
        term = -term * x * x / ((2 * k) * (2 * k + 1))
        total += term
    return total


def cos_series(x: float) -> float:
    """cos(x) from its Taylor series after reducing x into [-pi, pi]."""
    two_pi: float = 6.283185307179586
    while x > 3.141592653589793:
        x -= two_pi
    while x < -3.141592653589793:
        x += two_pi
    term: float = 1.0
    total: float = 1.0
    for k in range(1, 14):
        term = -term * x * x / ((2 * k - 1) * (2 * k))
        total += term
    return total


def dft_power(signal: list[float]) -> list[float]:
    """Power |X_k|^2 of the first n/2 + 1 DFT bins, with the twiddle factors generated by rotation."""
    n: int = len(signal)
    power: list[float] = []
    for k in range(n // 2 + 1):
        theta: float = 6.283185307179586 * k / n
        c: float = cos_series(theta)
        s: float = sin_series(theta)
        cr: float = 1.0
        ci: float = 0.0
        re: float = 0.0
        im: float = 0.0
        for t in range(n):
            re += signal[t] * cr
            im += signal[t] * ci
            nr: float = cr * c + ci * s
            ci = ci * c - cr * s
            cr = nr
        power.append(re * re + im * im)
    return power


def dominant_bin(power: list[float]) -> int:
    """Index of the strongest non-DC bin (lowest index on ties)."""
    best: int = 1
    for k in range(2, len(power)):
        if power[k] > power[best]:
            best = k
    return best


def median_filter(signal: list[float], window: int) -> list[float]:
    """Sliding median over an odd `window`; the ends use the samples that exist."""
    n: int = len(signal)
    half: int = window // 2
    out: list[float] = []
    for i in range(n):
        lo: int = max(0, i - half)
        hi: int = min(n - 1, i + half)
        buf: list[float] = []
        for j in range(lo, hi + 1):
            v: float = signal[j]
            buf.append(v)
            m: int = len(buf) - 1
            while m > 0 and buf[m - 1] > buf[m]:
                tmp: float = buf[m]
                buf[m] = buf[m - 1]
                buf[m - 1] = tmp
                m -= 1
        out.append(buf[len(buf) // 2])
    return out
