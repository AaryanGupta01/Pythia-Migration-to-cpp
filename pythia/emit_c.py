"""
PYTHIA :: Phase 5 -- Target Code Generation (PIR -> C11)
Owner: Member 4 (Aaryan Gupta)

Emits readable C++17 using the C++ runtime and lambda IIFEs for expression
scopes that need to evaluate an operand exactly once.
"""
import sys
from typing import List, Optional
from . import ast_nodes as A
from .typecheck import Ty, INT, FLOAT, BOOL, STR, NONE, ERR, TypeChecker
from . import builtins_ext as _bx
from . import tuples as _tup
from . import comprehensions as _comp

LIST_RT = {"int": "PyListI64", "float": "PyListF64",
           "bool": "PyListBool", "str": "PyListStr"}

DICT_RT = {
    ("int", "int"): "PyDictIntInt", ("int", "float"): "PyDictIntFloat",
    ("int", "bool"): "PyDictIntBool", ("int", "str"): "PyDictIntStr",
    ("str", "int"): "PyDictStrInt", ("str", "float"): "PyDictStrFloat",
    ("str", "bool"): "PyDictStrBool", ("str", "str"): "PyDictStrStr",
}


def is_obj_list(t: Optional[Ty]) -> bool:
    """list[SomeClass]: a typed PyList<std::shared_ptr<SomeClass>> driven by the generic pyl_* templates."""
    return (t is not None and t.name == "list" and t.elem is not None and t.elem.name not in LIST_RT
            and t.elem.name not in ("list", "dict", "set"))


def list_rt_name(t: Ty) -> str:
    """Runtime list type for list[elem]. Primitive elements are monomorphic
    (PyListI64 etc); anything else (nested list, class instance) is a
    pointer, so it rides the generic PyListList and gets cast at each use."""
    if t.elem is not None and t.elem.name in LIST_RT:
        return LIST_RT[t.elem.name]
    if t.elem is not None and t.elem.name == "tuple":
        return f"PyList<{ctype(t.elem).strip()}>"
    if is_obj_list(t):
        return f"PyList<std::shared_ptr<{t.elem.name}>>"
    return "PyListList"


def dict_rt_name(t: Ty) -> str:
    if _tup.generic_dict(t):
        return _tup.dict_t_name(t)
    return DICT_RT.get((t.key.name, t.elem.name)) or _tup.dict_t_name(t)   # any value type


def ctype(t: Optional[Ty]) -> str:
    if t is None or t is ERR:
        return "void"
    if t.name == "int":
        return "int64_t "
    if t.name == "float":
        return "double "
    if t.name == "bool":
        return "bool "
    if t.name == "str":
        return "PyStr *"
    if t.name == "None":
        return "void "
    if t.name == "list":
        return list_rt_name(t) + " *"
    if t.name == "dict":
        return dict_rt_name(t) + " *"
    ext = _ext.ctype(t)                       # Optional[T], set[T]
    if ext is not None:
        return ext
    if t.name == "tuple":
        return _tup.ctype_tuple(t)
    return f"std::shared_ptr<{t.name}>"  # class instances use RAII ownership


def zero(t: Ty) -> str:
    if t.name == "optional" and t.elem.name in ("int", "float", "bool"):
        return "std::nullopt"
    return {"int": "0", "float": "0.0", "bool": "false", "tuple": "{}"}.get(t.name, "NULL")


def c_string(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.extend(f"\\{b:03o}" for b in ch.encode("utf-8"))
    return '"' + "".join(out) + '"'


class Emitter:
    def __init__(self, tc: TypeChecker, library: bool = False,
                 track_lines: bool = False):
        self.tc = tc
        self.buf: List[str] = []
        self.tmp = 0
        self.wrappers: dict = {}      # str(elem_ty) -> (name, C source)
        # library mode: no main(); track_lines: remember which PySub line
        # produced each output line (off for the normal CLI path)
        self.library = library
        self.track = track_lines
        self.cur = 0
        self.src_of: List[int] = []   # parallel to buf when tracking
        self._fn = None               # FuncDef being emitted (None: module level)

    def w(self, indent: int, line: str = "") -> None:
        self.buf.append("    " * indent + line if line else "")
        if self.track:
            self.src_of.append(self.cur)

    def line_map(self) -> dict:
        """PySub line -> [1-based output lines] (only meaningful if tracking)."""
        out: dict = {}
        for i, ln in enumerate(self.src_of):
            if ln:
                out.setdefault(str(ln), []).append(i + 1)
        return out

    def fresh(self) -> str:
        self.tmp += 1
        return f"_t{self.tmp}"

    # ---- module ------------------------------------------------------------
    def emit_module(self, mod: A.Module, src_name: str) -> str:
        self.w(0, "/* ------------------------------------------------------------------")
        self.w(0, f" * Generated by PYTHIA 0.1 from {src_name}")
        self.w(0, " * Do not edit: regenerate with `python -m pythia.cli <source>.py`.")
        self.w(0, " * ---------------------------------------------------------------- */")
        self.w(0, '#include "pyrt.hpp"')
        self.w(0)
        wrapper_marker = len(self.buf)   # filled in once all wrappers are known

        if mod.classes:
            self.w(0, "/* class instances: generated C++ objects */")
            for c in mod.classes:
                self.cur = c.line
                self.w(0, f"typedef struct {c.name} {c.name};")
            self.cur = 0
            self.w(0)
            for c in mod.classes:
                self.cur = c.line
                self.emit_class_struct(c)
            self.cur = 0
            self.w(0)
            for c in mod.classes:
                self.cur = c.line
                self.w(0, self.ctor_signature(c) + ";")
                for m in c.methods:
                    self.cur = m.line
                    self.w(0, self.method_signature(c, m) + ";")
            self.cur = 0
            self.w(0)
            _cls.emit_decls(self, mod)        # class attributes, dispatchers, dunder helpers (classes_ext)

        if mod.funcs:
            self.w(0, "/* forward declarations (PySub allows mutual recursion) */")
            for f in mod.funcs:
                self.cur = f.line
                self.w(0, self.signature(f) + ";")
            self.cur = 0
            self.w(0)
        _ext.emit_globals(self, mod)      # module-level variables used by functions, mutable defaults

        for c in mod.classes:
            self.cur = c.line
            self.emit_class_ctor(c)
            self.cur = 0
            self.w(0)
            for m in c.methods:
                self.emit_func(m, owner=c.name)
                self.w(0)

        for f in mod.funcs:
            self.emit_func(f)
            self.w(0)
        if not self.library:
            self.emit_main(mod)
        elif _ext.hoisted(self):
            _ext.emit_lib_init(self, mod)
        if self.wrappers:
            wlines = ["/* print-adapter wrappers for nested/class containers */"]
            for _, body in self.wrappers.values():
                wlines.append(body)
            wlines.append("")
            self.buf[wrapper_marker:wrapper_marker] = wlines
            if self.track:
                self.src_of[wrapper_marker:wrapper_marker] = [0] * len(wlines)
        _tup.splice_dict_defs(self, wrapper_marker)
        pre = _ext.module_prelude(self, mod)      # classes a generic dict holds must be declared first
        if pre:
            self.buf[wrapper_marker:wrapper_marker] = pre
            if self.track:
                self.src_of[wrapper_marker:wrapper_marker] = [0] * len(pre)
        return "\n".join(self.buf) + "\n"

    # ---- classes -------------------------------------------------------
    @staticmethod
    def method_name(cls: str, m: str) -> str:
        return f"m_{cls}_{m}"

    def emit_class_struct(self, c: A.ClassDef) -> None:
        if _cls.emit_struct(self, c):         # struct D : B, run-time class id (classes_ext)
            return
        info = self.tc.classes[c.name]
        self.w(0, f"struct {c.name} {{")
        for name, t in zip(info.field_names, info.fields):
            self.w(1, f"{ctype(t)}{name};")
        self.w(0, "};")

    def ctor_signature(self, c: A.ClassDef) -> str:
        info = self.tc.classes[c.name]
        if info.init is None:
            return f"static std::shared_ptr<{c.name}> {c.name}_new(void)"
        ps = ", ".join(f"{ctype(t)}p_{p.name}" for p, t in
                       zip(info.init.node.params[1:], info.init.params))
        return f"static std::shared_ptr<{c.name}> {c.name}_new({ps or 'void'})"

    def emit_class_ctor(self, c: A.ClassDef) -> None:
        if _cls.emit_ctor(self, c):           # inherited __init__, class-attribute initial values
            return
        info = self.tc.classes[c.name]
        self.w(0, self.ctor_signature(c) + " {")
        self.w(1, f"auto p_self = std::make_shared<{c.name}>();")
        for name, t in zip(info.field_names, info.fields):
            self.w(1, f"p_self->{name} = {zero(t)};")
        if info.init is not None:
            args = ", ".join(f"p_{p.name}" for p in info.init.node.params[1:])
            call_args = "p_self" + (f", {args}" if args else "")
            self.w(1, f"{self.method_name(c.name, '__init__')}({call_args});")
        self.w(1, "return p_self;")
        self.w(0, "}")

    def method_signature(self, c: A.ClassDef, m: A.FuncDef) -> str:
        sig = self.tc.classes[c.name].methods[m.name]
        ps = ", ".join(f"{ctype(t)}p_{p.name}" for p, t in
                       zip(m.params[1:], sig.params))
        ps = f"std::shared_ptr<{c.name}> p_self" + (", " + ps if ps else "")
        return f"static {ctype(sig.ret)}{self.method_name(c.name, m.name)}({ps})"

    def signature(self, f: A.FuncDef) -> str:
        sig = self.tc.funcs[f.name]
        ps = ", ".join(f"{ctype(t)}p_{p.name}" for p, t in zip(f.params, sig.params))
        return f"static {ctype(sig.ret)}f_{f.name}({ps or 'void'})"

    def emit_func(self, f: A.FuncDef, owner: Optional[str] = None) -> None:
        self.cur = f.line
        self._emit_func(f, owner)
        self.cur = 0

    def _emit_func(self, f: A.FuncDef, owner: Optional[str] = None) -> None:
        self._fn = f
        if owner is not None:
            self.w(0, self.method_signature(self.tc.classes[owner].node, f) + " {")
            sig = self.tc.classes[owner].methods[f.name]
            locals_ = {k: v for k, v in f.locals_.items() if k != "self"}
        else:
            self.w(0, self.signature(f) + " {")
            sig = self.tc.funcs[f.name]
            locals_ = f.locals_
        for name, t in locals_.items():
            if t is ERR:
                continue
            self.w(1, f"{ctype(t)}p_{name} = {zero(t)};")
        if locals_:
            self.w(0)
        for s in f.body:
            self.stmt(s, 1)
        if sig.ret != NONE:
            self.w(1, f"return {zero(sig.ret)};   /* unreachable unless the result is Optional */")
        self.w(0, "}")
        self._fn = None

    def emit_main(self, mod: A.Module) -> None:
        self.w(0, "int main(void) {")
        self.w(1, f"pyrt_set_py_minor({sys.version_info.minor});   /* match this CPython's error texts */")
        self.w(1, "try {")
        for name, t in mod.globals_.items():
            if t is ERR or name in _ext.hoisted(self):
                continue
            self.w(2, f"{ctype(t)}p_{name} = {zero(t)};")
        if mod.globals_:
            self.w(0)
        for s in mod.main:
            self.stmt(s, 2)
        self.w(2, "return 0;")
        self.w(1, "} catch (const PythonException &exc) {")
        self.w(2, "py_print_exception(exc);")
        self.w(2, "return 1;")
        self.w(1, "}")
        self.w(0, "}")

    # ---- statements --------------------------------------------------------
    # ---- container access helpers ------------------------------------------
    def dict_set(self, base_c: str, base_ty: Ty, key_c: str, val_c: str) -> str:
        rt = dict_rt_name(base_ty)
        return f"{rt}_set({base_c}, {key_c}, {val_c});"

    def stmt(self, s: A.Node, d: int) -> None:
        if not self.track:
            self._stmt(s, d)
            return _ext.after_stmt(self, s, d)
        prev, self.cur = self.cur, s.line
        self._stmt(s, d)
        _ext.after_stmt(self, s, d)
        self.cur = prev

    def _stmt(self, s: A.Node, d: int) -> None:
        if _cls.stmt(self, s, d):             # class attributes, property setters, __setitem__, __iadd__
            return
        if _ext.stmt(self, s, d):             # in-place set |= ..., attribute stores on possibly-None objects
            return
        if isinstance(s, A.Assign):
            if isinstance(s.target, A.Subscript):
                base = s.target.value
                bt = base.ty
                if bt.name == "dict":
                    self.w(d, self.dict_set(self.ex(base), bt,
                                            self.ex(s.target.index), self.ex(s.value)))
                elif is_obj_list(bt):
                    self.w(d, f"pyl_set({self.ex(base)}, {self.ex(s.target.index)}, {self.ex(s.value)});")
                else:
                    rt = list_rt_name(bt)
                    vexpr = self.ex(s.value)
                    if rt == "PyListList":
                        vexpr = f"(void *)({vexpr})"
                    self.w(d, f"{rt}_set({self.ex(base)}, {self.ex(s.target.index)}, "
                              f"{vexpr});")
            elif isinstance(s.target, A.Attribute):
                self.w(d, f"{self.ex(s.target.value)}->{s.target.attr} = "
                          f"{self.ex(s.value)};")
            else:
                self.w(d, f"p_{s.target.id} = {self.ex(s.value)};")

        elif isinstance(s, A.AugAssign):
            fake = A.BinOp(s.line, s.col, op=s.op, left=s.target, right=s.value)
            fake.ty = s.target.ty
            if isinstance(s.target, A.Subscript):
                base = s.target.value
                bt = base.ty
                if bt.name == "dict":
                    self.w(d, self.dict_set(self.ex(base), bt,
                                            self.ex(s.target.index), self.binop(fake)))
                else:
                    rt = list_rt_name(bt)
                    vexpr = self.binop(fake)
                    if rt == "PyListList":
                        vexpr = f"(void *)({vexpr})"
                    self.w(d, f"{rt}_set({self.ex(base)}, {self.ex(s.target.index)}, "
                              f"{vexpr});")
            elif isinstance(s.target, A.Attribute):
                self.w(d, f"{self.ex(s.target.value)}->{s.target.attr} = "
                          f"{self.binop(fake)};")
            else:
                self.w(d, f"p_{s.target.id} = {self.binop(fake)};")

        elif isinstance(s, A.ExprStmt):
            v = s.value
            if isinstance(v, A.Call) and v.func == "print":
                self.emit_print(v, d)
            else:
                self.w(d, f"(void)({self.ex(v)});")

        elif isinstance(s, A.Return):
            if s.value is None:
                self.w(d, "return;")
            else:
                self.w(d, f"return {self.ex(s.value)};")

        elif isinstance(s, A.If):
            self.w(d, f"if ({self.cond(s.test)}) {{")
            for x in s.body:
                self.stmt(x, d + 1)
            if s.orelse:
                self.w(d, "} else {")
                for x in s.orelse:
                    self.stmt(x, d + 1)
            self.w(d, "}")

        elif isinstance(s, A.While):
            self.w(d, f"while ({self.cond(s.test)}) {{")
            for x in s.body:
                self.stmt(x, d + 1)
            self.w(d, "}")

        elif isinstance(s, A.ForRange):
            stop, step, ctr = self.fresh(), self.fresh(), self.fresh()
            self.w(d, "{")
            self.w(d + 1, f"int64_t {stop} = {self.ex(s.stop)};")
            self.w(d + 1, f"int64_t {step} = "
                          f"{self.ex(s.step) if s.step is not None else '1'};")
            self.w(d + 1, f'if ({step} == 0) py_raise("ValueError", '
                          f'"range() arg 3 must not be zero");')
            # Python precomputes the range sequence: the loop runs a fixed
            # number of times and rebinds the loop variable from that
            # sequence each pass, regardless of what the body does to it.
            # A C for-loop that reuses p_<var> as its own induction variable
            # would let a body reassignment corrupt the iteration count (up
            # to an infinite loop) -- so the *hidden* counter drives the
            # loop, and p_<var> is just assigned from it each iteration.
            self.w(d + 1, f"for (int64_t {ctr} = {self.ex(s.start)};")
            self.w(d + 1, f"     {step} > 0 ? {ctr} < {stop} : {ctr} > {stop};")
            self.w(d + 1, f"     {ctr} += {step}) {{")
            self.w(d + 2, f"p_{s.var} = {ctr};")
            for x in s.body:
                self.stmt(x, d + 2)
            self.w(d + 1, "}")
            self.w(d, "}")

        elif isinstance(s, A.ForEach) and _comp.is_special_foreach(self.tc, s):
            _comp.emit_foreach(self, s, d)

        elif isinstance(s, A.ForEach):
            it, idx = self.fresh(), self.fresh()
            t = s.iter.ty
            self.w(d, "{")
            if t.name == "list":
                rt = list_rt_name(t)
                self.w(d + 1, f"{rt} *{it} = {self.ex(s.iter)};")
                self.w(d + 1, f"for (int64_t {idx} = 0; {idx} < static_cast<int64_t>({it}->data.size()); {idx}++) {{")
                if rt == "PyListList":
                    self.w(d + 2, f"p_{s.var} = ({ctype(t.elem)}){it}->data[{idx}];")
                else:
                    self.w(d + 2, f"p_{s.var} = {it}->data[{idx}];")
            elif t.name == "dict":
                rt = dict_rt_name(t)
                self.w(d + 1, f"{rt} *{it} = {self.ex(s.iter)};")
                self.w(d + 1, f"for (int64_t {idx} = 0; {idx} < {it}->size(); {idx}++) {{")
                self.w(d + 2, f"p_{s.var} = {it}->keys[{idx}];")
            else:
                self.w(d + 1, f"PyStr *{it} = {self.ex(s.iter)};")
                self.w(d + 1, f"for (int64_t {idx} = 0; {idx} < static_cast<int64_t>({it}->data.size()); {idx}++) {{")
                self.w(d + 2, f"p_{s.var} = pystr_new({it}->data.data() + {idx}, 1);")
            for x in s.body:
                self.stmt(x, d + 2)
            self.w(d + 1, "}")
            self.w(d, "}")

        elif isinstance(s, A.Break):
            self.w(d, "break;")
        elif isinstance(s, A.Continue):
            self.w(d, "continue;")
        elif isinstance(s, A.Pass):
            self.w(d, ";")

        elif isinstance(s, A.TryExcept):
            self.w(d, "{")
            self.w(d + 1, "try {")
            for x in s.body:
                self.stmt(x, d + 2)
            self.w(d + 1, "} catch (const PythonException &exc) {")
            named = [hd for hd in s.handlers if hd.exc_name is not None]
            bare = [hd for hd in s.handlers if hd.exc_name is None]
            for i, hd in enumerate(named):
                kw = "if" if i == 0 else "} else if"
                self.w(d + 2, f'{kw} (exc.name() == "{hd.exc_name}") {{')
                if hd.bind:
                    self.w(d + 3, f"PyStr *p_{hd.bind} = pystr_lit(exc.message().c_str());")
                for x in hd.body:
                    self.stmt(x, d + 3)
            if named:
                if bare:
                    self.w(d + 2, "} else {")
                    if bare[0].bind:
                        self.w(d + 3, f"PyStr *p_{bare[0].bind} = pystr_lit(exc.message().c_str());")
                    for x in bare[0].body:
                        self.stmt(x, d + 3)
                    self.w(d + 2, "}")
                else:
                    self.w(d + 2, "} else {")
                    self.w(d + 3, "throw;")
                    self.w(d + 2, "}")
            elif bare:
                if bare[0].bind:
                    self.w(d + 2, f"PyStr *p_{bare[0].bind} = pystr_lit(exc.message().c_str());")
                for x in bare[0].body:
                    self.stmt(x, d + 2)
            self.w(d + 1, "}")
            self.w(d, "}")

        elif isinstance(s, A.Raise):
            msg = self.ex(s.message) if s.message is not None else 'pystr_lit("")'
            self.w(d, f'py_raise_pystr("{s.exc_name}", {msg});')

    def kwarg(self, e: A.Node, name: str) -> Optional[A.Node]:
        for kw in getattr(e, "kwargs", None) or []:
            if kw.name == name:
                return kw.value
        return None

    @staticmethod
    def _has_call(n) -> bool:
        if isinstance(n, (A.Call, A.MethodCall)):
            return True
        if isinstance(n, A.Subscript) and n.value.ty is not None and n.value.ty.name == "dict":
            return True                   # d[k] may insert (defaultdict)
        if isinstance(n, A.Node):
            return any(Emitter._has_call(getattr(n, f)) for f in n.__dataclass_fields__ if f != "ty")
        if isinstance(n, list):
            return any(Emitter._has_call(x) for x in n)
        return False

    def emit_print(self, call: A.Call, d: int) -> None:
        sep, end = self.kwarg(call, "sep"), self.kwarg(call, "end")
        # CPython evaluates every argument before printing anything: print(xs, xs.pop()) shows the popped xs.
        eager = len(call.args) > 1 and any(self._has_call(a) for a in call.args[1:])
        if sep is not None or end is not None or eager:
            self.w(d, "{")
            vals = []
            for a in call.args:
                if eager:
                    v = self.fresh()
                    self.w(d + 1, f"{ctype(a.ty)}{v} = {self.ex(a)};")
                    vals.append(v)
                else:
                    vals.append(None)
            sv = ev = None
            if sep is not None:
                sv = self.fresh()
                self.w(d + 1, f"PyStr *{sv} = {self.ex(sep)};")
            if end is not None:
                ev = self.fresh()
                self.w(d + 1, f"PyStr *{ev} = {self.ex(end)};")
            self.w(d + 1, "py_print_begin();")
            for a, v in zip(call.args, vals):
                self.w(d + 1, f"py_print_sep_s({sv});" if sv else "py_print_sep();")
                self.w(d + 1, self.print_call(a, v) + ";")
            self.w(d + 1, f"py_print_end_s({ev});" if ev else "py_print_end();")
            self.w(d, "}")
            return
        self.w(d, "py_print_begin();")
        for a in call.args:
            self.w(d, "py_print_sep();")
            self.w(d, self.print_call(a) + ";")
        if not call.args:
            pass
        self.w(d, "py_print_end();")

    def print_call(self, a: A.Node, value: Optional[str] = None) -> str:
        ext = _cls.print_call(self, a, value)     # objects via __str__ / __repr__
        if ext is not None:
            return ext
        ext = _ext.print_call(self, a, value)     # Optional values, dicts of lists/dicts
        if ext is not None:
            return ext
        t, e = a.ty, (value if value is not None else self.ex(a))
        if _tup.involves_tuple(t):
            return f"py_print_repr({e})"
        if t == INT:
            return f"py_print_i64({e})"
        if t == FLOAT:
            return f"py_print_f64({e})"
        if t == BOOL:
            return f"py_print_bool({e})"
        if t == STR:
            return f"py_print_str({e})"
        if t.name == "list":
            rt = list_rt_name(t)
            if rt != "PyListList":
                suffix = {"int": "i64", "float": "f64", "bool": "bool", "str": "str"}[t.elem.name]
                return f"py_print_list_{suffix}({e})"
            wrapper = self.print_wrapper_for(t.elem)
            return f"py_print_list_generic({e}, {wrapper})"
        if t.name == "dict":
            suffix = {"int": "int", "str": "str"}[t.key.name] + \
                     {"int": "int", "float": "float", "bool": "bool", "str": "str"}[t.elem.name]
            return f"py_print_dict_{suffix}({e})"
        return f"(void)({e})"

    def print_wrapper_for(self, elem_ty: Ty) -> str:
        """A single-level list[T] prints via py_print_list_<T> directly; a
        nested/class list stores void* and needs an adapter matching
        py_print_list_generic's void(*)(void*) callback signature. Wrappers
        are collected as they're discovered and spliced in after the
        #include, so forward reference is never an issue."""
        key = str(elem_ty)
        if key in self.wrappers:
            return self.wrappers[key][0]
        name = f"pw_{len(self.wrappers) + 1}"
        rt = list_rt_name(elem_ty) if elem_ty.name == "list" else None
        if elem_ty.name == "list" and rt != "PyListList":
            suffix = {"int": "i64", "float": "f64", "bool": "bool", "str": "str"}[elem_ty.elem.name]
            body = (f"static void {name}(void *p) {{ "
                    f"py_print_list_{suffix}(({rt} *)p); }}")
        else:
            # Reached only if the type checker ever allows printing a list
            # of class instances or triple-nested lists; both are refused
            # at the type-check stage today (no reproducible repr / depth
            # cap), so this path exists for forward compatibility only.
            body = f"static void {name}(void *p) {{ (void)p; }}"
        self.wrappers[key] = (name, body)
        return name

    # ---- conditions --------------------------------------------------------
    def cond(self, e: A.Node) -> str:
        """Boolean context: short-circuit maps straight onto C's && / ||."""
        if isinstance(e, A.BoolOp):
            op = "&&" if e.op == "and" else "||"
            return "(" + f" {op} ".join(self.cond(v) for v in e.values) + ")"
        if isinstance(e, A.UnaryOp) and e.op == "not":
            return f"(!{self.cond(e.operand)})"
        if isinstance(e, A.Coerce):
            return self.cond(e.value)
        return self.truthy(self.ex(e), e.ty)

    @staticmethod
    def truthy(expr: str, t: Optional[Ty]) -> str:
        if t is None or t is ERR:
            return "false"
        ext = _cls.truthy(expr, t)            # __bool__ / __len__
        if ext is not None:
            return ext
        ext = _ext.truthy(expr, t)
        if ext is not None:
            return ext
        if t == BOOL:
            return f"({expr})"
        if t == INT:
            return f"(({expr}) != 0)"
        if t == FLOAT:
            return f"(({expr}) != 0.0)"
        if t == STR:
            return f"pystr_truthy({expr})"
        if t.name in ("list", "dict", "set"):
            return f"(({expr})->size() != 0)"
        if t.name == "tuple":
            return f"pyt_truthy({expr})"
        return "true"          # class instances: always truthy (no __bool__/__len__ in PySub)

    # ---- expressions -------------------------------------------------------
    def ex(self, e: Optional[A.Node]) -> str:
        if e is None:
            return "0"
        ext = _cls.ex(self, e)                # user-class constructs (classes_ext)
        if ext is not None:
            return ext
        ext = _ext.ex(self, e)                # None, narrowed names, sets, isinstance, defaults ...
        if ext is not None:
            return ext
        if isinstance(e, A.IntLit):
            if e.value == -(2 ** 63):
                return "INT64_MIN"
            return f"INT64_C({e.value})"
        if isinstance(e, A.FloatLit):
            return repr(float(e.value))
        if isinstance(e, A.BoolLit):
            return "true" if e.value else "false"
        if isinstance(e, A.StrLit):
            return f"pystr_lit({c_string(e.value)})"
        if isinstance(e, A.NoneLit):
            return "0"
        if isinstance(e, A.Name):
            return f"p_{e.id}"
        if isinstance(e, A.TupleLit):
            return _tup.emit_lit(self, e)

        if isinstance(e, A.Coerce):
            inner = self.ex(e.value)
            if e.to == FLOAT:
                return f"((double)({inner}))"
            if e.to == INT:
                return f"((int64_t)({inner}))"
            if e.to == BOOL:
                return self.truthy(inner, e.value.ty)
            return inner

        if isinstance(e, A.BinOp):
            return self.binop(e)

        if isinstance(e, A.Compare):
            if e.right.ty.name == "tuple" or (e.left.ty.name == "tuple" and e.op not in ("in", "not in")):
                return _tup.emit_compare(self, e)
            l, r, lt = self.ex(e.left), self.ex(e.right), e.left.ty
            if e.op in ("in", "not in"):
                rt = e.right.ty
                if rt.name == "dict":
                    drt = dict_rt_name(rt)
                    test = f"{drt}_contains({r}, {l})"
                elif is_obj_list(rt):
                    test = f"pyl_contains({r}, {l})"
                elif rt.name == "list":
                    lrt = list_rt_name(rt)
                    test = f"{lrt}_contains({r}, {l})"
                else:  # str in str
                    test = f"pystr_contains({r}, {l})"
                return test if e.op == "in" else f"(!{test})"
            if lt == STR:
                return f"(pystr_cmp({l}, {r}) {e.op} 0)"
            if is_obj_list(lt):
                eq = f"pyl_eq({l}, {r})"
                return eq if e.op == "==" else f"(!{eq})"
            if lt.name == "list":
                rt = list_rt_name(lt)
                if rt == "PyListList":
                    return f"(({l}) {e.op} ({r}))"   # unreachable: only ==/!= allowed, and PyListList isn't compared today
                eq = f"{rt}_eq({l}, {r})"
                return eq if e.op == "==" else f"(!{eq})"
            return f"(({l}) {e.op} ({r}))"

        if isinstance(e, A.IfExp):              # C's ?: evaluates only the chosen branch, like Python
            return f"({self.cond(e.test)} ? ({self.ex(e.body)}) : ({self.ex(e.orelse)}))"

        if isinstance(e, A.BoolOp):
            t = e.ty
            v = self.fresh()
            a, b = self.ex(e.values[0]), self.ex(e.values[1])
            test = self.truthy(v, t)
            body = f"{test} ? ({b}) : {v}" if e.op == "and" else f"{test} ? {v} : ({b})"
            return f"[&]() {{ {ctype(t)}{v} = ({a}); return {body}; }}()"

        if isinstance(e, A.UnaryOp):
            if e.op == "not":
                return f"(!{self.truthy(self.ex(e.operand), e.operand.ty)})"
            if e.op == "+":
                return self.ex(e.operand)
            if e.op == "~":
                return f"(~((int64_t)({self.ex(e.operand)})))"
            if e.ty == INT:
                return f"py_neg_i64({self.ex(e.operand)})"
            return f"(-({self.ex(e.operand)}))"

        if isinstance(e, A.Subscript):
            bt = e.value.ty
            if bt.name == "tuple":
                return f"std::get<{e.tuple_index}>({self.ex(e.value)})"
            if bt == STR:
                return f"pystr_index({self.ex(e.value)}, {self.ex(e.index)})"
            if bt.name == "dict":
                rt = dict_rt_name(bt)
                return f"{rt}_get({self.ex(e.value)}, {self.ex(e.index)})"
            if is_obj_list(bt):
                return f"pyl_get({self.ex(e.value)}, {self.ex(e.index)})"
            rt = list_rt_name(bt)
            if rt == "PyListList":
                return (f"({ctype(bt.elem)})PyListList_get({self.ex(e.value)}, "
                        f"{self.ex(e.index)})")
            return f"{rt}_get({self.ex(e.value)}, {self.ex(e.index)})"

        if isinstance(e, A.ListLit):
            rt = list_rt_name(e.ty)
            v = self.fresh()
            if is_obj_list(e.ty):
                el = ctype(e.ty.elem).strip()
                parts = [f"auto *{v} = pyl_new<{el}>();"]
                parts += [f"pyl_append({v}, {self.ex(x)});" for x in e.elts]
                return "[&]() { " + " ".join(parts) + f" return {v}; }}()"
            if rt == "PyListList":
                parts = [f"PyListList *{v} = PyListList_new();"]
                parts += [f"PyListList_append({v}, (void *)({self.ex(x)}));" for x in e.elts]
            else:
                parts = [f"{rt} *{v} = {rt}_new();"]
                parts += [f"{rt}_append({v}, {self.ex(x)});" for x in e.elts]
            return "[&]() { " + " ".join(parts) + f" return {v}; }}()"

        if isinstance(e, A.DictLit):
            rt = dict_rt_name(e.ty)
            v = self.fresh()
            parts = [f"{rt} *{v} = {rt}_new();"]
            parts += [f"{rt}_set({v}, {self.ex(k)}, {self.ex(val)});"
                     for k, val in zip(e.keys, e.values)]
            return "[&]() { " + " ".join(parts) + f" return {v}; }}()"

        if isinstance(e, A.Attribute):
            return f"{self.ex(e.value)}->{e.attr}"

        if isinstance(e, A.MethodCall):
            _r = _bx.emit_method(self, e)
            if _r is not None:
                return _r
            recv, rt_ = self.ex(e.recv), e.recv.ty
            if rt_.name == "list" and (is_obj_list(rt_) or e.method not in ("append", "pop") or e.args):
                return self.list_method(e, recv, rt_)
            if rt_.name == "list":
                rt = list_rt_name(rt_)
                if e.method == "append":
                    v = self.ex(e.args[0])
                    if rt == "PyListList":
                        v = f"(void *)({v})"
                    return f"({rt}_append({recv}, {v}), 0)"
                if e.method == "pop":
                    if rt == "PyListList":
                        return f"({ctype(rt_.elem)})PyListList_pop({recv})"
                    return f"{rt}_pop({recv})"
            if rt_.name == "dict":
                drt = dict_rt_name(rt_)
                if e.method == "items":
                    return f"pyd_items({recv})"
                if e.method == "get":
                    return (f"{drt}_get_default({recv}, {self.ex(e.args[0])}, "
                            f"{self.ex(e.args[1])})")
            if rt_ == STR:
                m, args = e.method, [self.ex(a) for a in e.args]
                if m in ("strip", "lstrip", "rstrip") and args:
                    return f"pystr_{m}_chars({recv}, {args[0]})"
                if m == "split":
                    return f"pystr_split({recv}, {args[0]})" if args else f"pystr_split_ws({recv})"
                if m == "index":
                    return f"pystr_index_of({recv}, {args[0]})"
                return f"pystr_{m}({recv}" + "".join(", " + a for a in args) + ")"
            if rt_.name in self.tc.classes:
                mname = self.method_name(rt_.name, e.method)
                args = ", ".join(self.ex(a) for a in e.args)
                return f"{mname}({recv}" + (f", {args})" if args else ")")
            return "0"

        if isinstance(e, A.Call):
            if e.func in self.tc.classes:
                args = ", ".join(self.ex(a) for a in e.args)
                return f"{e.func}_new({args})"
            return self.call(e)

        if _comp.is_comp_node(e):
            return _comp.emit_expr(self, e)
        return "0"

    def list_method(self, e: A.MethodCall, recv: str, t: Ty) -> str:
        nested = list_rt_name(t) == "PyListList"

        def val(x: A.Node) -> str:
            v = self.ex(x)
            return f"(void *)({v})" if nested else v
        m = e.method
        if m == "append":
            return f"(pyl_append({recv}, {val(e.args[0])}), 0)"
        if m == "pop":
            call = f"pyl_pop_at({recv}, {self.ex(e.args[0])})" if e.args else f"pyl_pop({recv})"
            return f"({ctype(t.elem)}){call}" if nested else call
        if m == "insert":
            return f"(pyl_insert({recv}, {self.ex(e.args[0])}, {val(e.args[1])}), 0)"
        if m == "extend":
            return f"(pyl_extend({recv}, {self.ex(e.args[0])}), 0)"
        if m in ("clear", "reverse"):
            return f"(pyl_{m}({recv}), 0)"
        if m == "copy":
            return f"pyl_copy({recv})"
        if m in ("index", "count"):
            return f"pyl_{m}({recv}, {val(e.args[0])})"
        if m == "remove":
            return f"(pyl_remove({recv}, {val(e.args[0])}), 0)"
        if m == "sort" and self.kwarg(e, "key") is not None:
            return _comp.emit_sort_key(self, e, recv)
        if m == "sort":
            rev = self.kwarg(e, "reverse")
            return f"(pyl_sort({recv}, {self.ex(rev) if rev is not None else 'false'}), 0)"
        return "0"

    @staticmethod
    def _int_operand(x: A.Node) -> bool:
        if isinstance(x, A.Coerce):
            x = x.value
        return x.ty is not None and x.ty.name in ("int", "bool")

    def binop(self, e: A.BinOp) -> str:
        ext = _cls.emit_binop(self, e)        # __add__ / __radd__ ... on user classes
        if ext is not None:
            return ext
        op, t = e.op, e.ty
        if t.name == "tuple":                   # concatenation; operands evaluated left to right
            return f"[&]() {{ auto _a = {self.ex(e.left)}; auto _b = {self.ex(e.right)}; return std::tuple_cat(_a, _b); }}()"
        l, r = self.ex(e.left), self.ex(e.right)
        lt = e.left.ty
        if op in _bx.BITOPS:
            return _bx.emit_bitop(self, e, l, r)
        if op == "+" and t == STR:
            return f"pystr_concat({l}, {r})"
        if op == "+" and is_obj_list(t):
            return f"pyl_concat({l}, {r})"
        if op == "+" and t.name == "list":
            rt = list_rt_name(t)
            if rt == "PyListList":
                return f"PyListList_concat({l}, {r})"
            return f"{rt}_concat({l}, {r})"
        if op == "*" and t == STR:
            return (f"pystr_repeat({l}, {r})" if lt == STR
                    else f"pystr_repeat({r}, {l})")
        if op == "*" and t.name == "list":
            return f"pyl_repeat({l}, {r})" if lt.name == "list" else f"pyl_repeat({r}, {l})"
        if t == FLOAT or op == "/":
            fn = {"+": None, "-": None, "*": None,
                  "/": "py_truediv", "//": "py_floordiv_f64",
                  "%": "py_mod_f64", "**": "px_pow_f64"}.get(op)
            if op == "/" and all(self._int_operand(x) for x in (e.left, e.right)):
                fn = "py_truediv_ii"                       # CPython words int/int and float division differently
            if fn:
                return f"{fn}({l}, {r})"
            return f"(({l}) {op} ({r}))"
        fn = {"+": "py_add_i64", "-": "py_sub_i64", "*": "py_mul_i64",
              "//": "py_floordiv_i64", "%": "py_mod_i64",
              "**": "py_pow_i64"}.get(op)
        if getattr(e, "no_guard", False) and op in ("+", "-", "*"):
            return f"(({l}) {op} ({r}))"    # proven safe by interval analysis
        return f"{fn}({l}, {r})" if fn else f"(({l}) {op} ({r}))"

    def call(self, e: A.Call) -> str:
        n = e.func
        tup = _tup.emit_call(self, e)
        if tup is not None:
            return tup
        _r = _bx.emit_call(self, e)
        if _r is not None:
            return _r
        hooked = _comp.emit_call_hook(self, e)
        if hooked is not None:
            return hooked
        if n == "len":
            a = e.args[0]
            return (f"pystr_len({self.ex(a)})" if a.ty == STR
                    else f"(({self.ex(a)})->size())")
        if n in ("ord", "chr"):
            return f"py_{n}({self.ex(e.args[0])})"
        if n == "abs":
            a = e.args[0]
            return (f"py_abs_i64({self.ex(a)})" if e.ty == INT
                    else f"fabs({self.ex(a)})")
        if n in ("min", "max") and len(e.args) == 1:
            return f"pyl_{n}({self.ex(e.args[0])})"
        if n in ("min", "max") and (len(e.args) > 2 or e.ty == STR):
            t = ctype(e.ty)                                    # fold left exactly like CPython: replace on strict < / >
            r = self.fresh()
            parts = [f"{t}{r} = ({self.ex(e.args[0])});"]
            for a in e.args[1:]:
                x = self.fresh()
                better = (f"pystr_cmp({x}, {r}) {'<' if n == 'min' else '>'} 0" if e.ty == STR
                          else f"{x} {'<' if n == 'min' else '>'} {r}")
                parts.append(f"{{ {t}{x} = ({self.ex(a)}); if ({better}) {r} = {x}; }}")
            return "[&]() { " + " ".join(parts) + f" return {r}; }}()"
        if n == "input":
            prompt = self.ex(e.args[0]) if e.args else 'pystr_lit("")'
            return f"py_input({prompt})"
        if n == "format":
            v = e.args[0]
            fn = {"int": "py_format_i64", "float": "py_format_f64", "str": "py_format_str",
                  "bool": "py_format_bool"}[v.ty.name]
            return f"{fn}({self.ex(v)}, {self.ex(e.args[1])})"
        if n == "round":
            a = e.args[0]
            if len(e.args) == 1:
                return f"py_round_i64({self.ex(a)})" if a.ty == FLOAT else f"((int64_t)({self.ex(a)}))"
            nd = self.ex(e.args[1])
            if a.ty == FLOAT:
                return f"py_round_f64({self.ex(a)}, {nd})"
            return f"py_round_int_n((int64_t)({self.ex(a)}), {nd})"
        if n == "sum":
            fn = {"int": "py_sum_i64", "float": "py_sum_f64", "bool": "py_sum_bool"}[e.args[0].ty.elem.name]
            return f"{fn}({self.ex(e.args[0])})"
        if n in ("sorted", "list"):
            a = e.args[0]
            src = {"str": "pyl_chars", "dict": "pyl_keys"}.get(a.ty.name)
            if n == "list":
                return f"{src or 'pyl_copy'}({self.ex(a)})"
            rev = self.kwarg(e, "reverse")
            lst = f"{src}({self.ex(a)})" if src else self.ex(a)
            return f"pyl_sorted({lst}, {self.ex(rev) if rev is not None else 'false'})"
        if n in ("min", "max"):
            t = ctype(e.ty)
            x, y = self.fresh(), self.fresh()
            cmp = "<" if n == "min" else ">"
            return (f"[&]() {{ {t}{x} = ({self.ex(e.args[0])}); "
                    f"{t}{y} = ({self.ex(e.args[1])}); "
                    f"return {x} {cmp} {y} ? {x} : {y}; }}()")
        if n == "int":
            a = e.args[0]
            if a.ty == STR:
                return f"py_i64_from_str({self.ex(a)})"
            return f"((int64_t)({self.ex(a)}))"
        if n == "float":
            a = e.args[0]
            if a.ty == STR:
                return f"py_f64_from_str({self.ex(a)})"
            return f"((double)({self.ex(a)}))"
        if n == "str":
            a = e.args[0]
            m = {"int": "pystr_from_i64", "float": "pystr_from_f64",
                 "bool": "pystr_from_bool", "str": None}[a.ty.name]
            return self.ex(a) if m is None else f"{m}({self.ex(a)})"
        if n == "bool":
            a = e.args[0]
            return self.truthy(self.ex(a), a.ty)
        args = ", ".join(self.ex(a) for a in e.args)
        return f"f_{n}({args})"


from . import emit_ext as _ext  # noqa: E402  (PySub 1.3 code generation)
from . import classes_ext as _cls  # noqa: E402  (user classes)


def emit(mod: A.Module, tc: TypeChecker, src_name: str,
         library: bool = False, line_map: Optional[dict] = None) -> str:
    """library=True omits main(); passing a dict as line_map fills it with
    PySub line -> [output lines] (both off for the normal CLI path)."""
    e = Emitter(tc, library=library, track_lines=line_map is not None)
    out = e.emit_module(mod, src_name)
    if line_map is not None:
        line_map.update(e.line_map())
    return out
