"""
PYTHIA :: user-class objects in library mode (pybind wrappers generated by libmode.py)

Objects cross the boundary as REAL instances of the user's own Python classes:

  * in:  a Python object is converted field by field (getattr) into the C++ object, once per call -- a memo keeps
         identity, so shared and cyclic object graphs (doubly linked lists, parent pointers) keep their shape.  Only
         instances whose type is exactly a compiled class are accepted; anything else (a Python subclass, a missing
         attribute, an unconvertible field) raises FallbackError before any compiled code runs.
  * out: after the call (also when it raises) every inbound object gets its fields written back (setattr; list /
         dict / set fields are updated in place, keeping their identity); objects the compiled code created become
         new instances of the user's class (cls.__new__(cls) + setattr, without running __init__ again).
  * class attributes are read from the Python class before the call and written back after it.

The Python classes are looked up by name in a dict handed to `_pythia_bind_classes(globals())` (the accel shim does
this with the decorated function's module globals); until then calls that need them raise FallbackError.
Exposed names: "C.m" (an instance method, called with self first; Python name `C__m`) and static/class methods.
"""
from typing import Dict, List, Optional, Set, Tuple

from . import ast_nodes as A
from .typecheck import Ty
from .types_ext import is_class, walk
from . import classes_ext as _ce


def py_name(name: str) -> str:
    """Python-visible attribute of the compiled module for an exposed name ("C.m" -> "C__m")."""
    return name.replace(".", "__")


def exposed_names(names) -> Set[str]:
    return {py_name(n) for n in names}


def trait(t: Ty, base_trait) -> Optional[str]:
    """pyb trait for a class type / list of a class type (None if not marshallable)."""
    tc = _ce._cur()
    if tc is None or getattr(tc, "cx", None) is None:
        return None
    if is_class(t) and t.name in tc.classes:
        return f"pyc_T_{t.name}" if t.name in marshallable(tc) else None
    if t.name == "list" and t.elem is not None and is_class(t.elem) and t.elem.name in tc.classes:
        inner = trait(t.elem, base_trait)
        return f"pyb::List<{inner}, PyList<std::shared_ptr<{t.elem.name}>>>" if inner else None
    return None


def marshallable(tc) -> Set[str]:
    """Classes whose every field (and every subclass) can cross the boundary."""
    cached = getattr(tc, "_lib_marsh", None)
    if cached is not None:
        return cached
    from .libmode import _trait
    cx = tc.cx
    ok = set(cx.order)
    tc._lib_marsh = ok                     # provisional: recursive class references resolve optimistically
    changed = True
    while changed:
        changed = False
        for c in list(ok):
            info = tc.classes[c]
            bad = any(_trait(t) is None for t in info.fields) or any(d not in ok for d in cx.below(c))
            if bad:
                ok.discard(c)
                changed = True
    tc._lib_marsh = ok
    return ok


def why_not(tc, t: Ty) -> str:
    from .libmode import _trait
    name = t.elem.name if t.name == "list" else t.name
    cx = tc.cx
    for c in [name] + cx.below(name):
        info = tc.classes[c]
        for n, ft in zip(info.field_names, info.fields):
            if _trait(ft) is None:
                return f"class {c}: field {n!r} of type {ft} cannot cross the Python boundary"
    return "class marshalling not supported"


def find_exposed(mod, tc, name: str):
    """(FuncDef, sig, owner_class_or_None) for an exposed name; None if there is no such function / method."""
    if "." not in name:
        f = next((g for g in mod.funcs if g.name == name), None)
        return (f, tc.funcs[name], None) if f is not None else None
    cls, m = name.split(".", 1)
    cx = getattr(tc, "cx", None)
    if cx is None or cls not in cx.defs:
        return None
    hit = cx.statics.get(cls, {}).get(m)
    if hit is not None:
        f = next(g for g in mod.funcs if g.name == hit[0])
        return f, tc.funcs[hit[0]], None
    f = next((g for g in cx.defs[cls].methods if g.name == m), None)
    if f is None or m == "__init__" or m in cx.props.get(cls, {}) or m.endswith("__set"):
        return None
    return f, tc.classes[cls].methods[m], cls


def involves_class(tc, t: Optional[Ty]) -> bool:
    if t is None:
        return False
    if is_class(t) and t.name in tc.classes:
        return True
    return any(involves_class(tc, x) for x in (t.elem, t.key) if x is not None) or \
        any(involves_class(tc, x) for x in (t.elts or ()))


def uses_cattrs(tc) -> bool:
    cx = getattr(tc, "cx", None)
    return cx is not None and any(cx.cattr.get(c) for c in cx.order)


def needs_objects(tc, sig, owner) -> bool:
    return owner is not None or uses_cattrs(tc) or any(involves_class(tc, t) for t in list(sig.params) + [sig.ret])


# ------------------------------------------------------------------------------------------- C++ glue
def _container(t: Ty) -> bool:
    return t.name in ("list", "dict", "set") or (t.name == "optional" and t.elem.name in ("list", "dict", "set"))


def _strict(tr: str) -> str:
    """Attribute traits: exact Python types (I64x / F64x), since attributes are written back after the call."""
    import re
    return re.sub(r"pyb::(I64|F64)\b", r"pyb::\1x", tr)


def _root(cx, c: str) -> str:
    return cx.mro(c)[-1]


def glue(tc) -> List[str]:
    """Per-class traits, the bound-class table, class-attribute sync; emitted once after the bridge include."""
    cx = getattr(tc, "cx", None)
    if cx is None or not cx.order:
        return []
    from .libmode import _trait
    ok = marshallable(tc)
    names = list(cx.order)
    idx = {c: i for i, c in enumerate(names)}
    out = ["// ---- user-class objects (classes_lib.py) ----",
           f"static PyObject *pyc_bound[{len(names)}] = {{{', '.join('nullptr' for _ in names)}}};",
           f"static const char *const pyc_bound_names[{len(names)}] = {{{', '.join(chr(34) + n + chr(34) for n in names)}}};",
           "static void pyc_need_bound() {",
           f"    for (int i = 0; i < {len(names)}; ++i)",
           "        if (!pyc_bound[i]) pyb::fallback(\"the module's Python classes are not bound (_pythia_bind_classes)\");",
           "}"]
    for c in names:
        if c in ok:
            out.append(f"struct pyc_T_{c} {{ using C = std::shared_ptr<::{c}>; static C in(PyObject *o); "
                       f"static PyObject *out(const C &p); }};")
    for c in names:
        if c not in ok:
            continue
        info = tc.classes[c]
        root = _root(cx, c)
        key = f"static_cast<const void *>(static_cast<::{root} *>(p.get()))"
        out.append(f"static void pyc_back_{c}(PyObject *o, const std::shared_ptr<::{c}> &p) {{")
        for n, t in zip(info.field_names, info.fields):
            fn = "put_cont" if _container(t) else "put_field"
            out.append(f"    pyb::{fn}<{_strict(_trait(t))}>(o, \"{n}\", p->{n});")
        out.append("}")
        out.append(f"static std::shared_ptr<::{c}> pyc_in_{c}(PyObject *o) {{")
        out.append("    pyb::ObjCtx *cx = pyb::objctx();")
        out.append(f"    auto p = std::make_shared<::{c}>();")
        if c in cx.cid:
            out.append(f"    p->_cid = {cx.cid[c]};")
        out.append(f"    cx->in[o] = std::static_pointer_cast<void>(std::static_pointer_cast<::{root}>(p));")
        out.append(f"    cx->out[{key}] = o;")
        out.append("    cx->keep.push_back(py::reinterpret_borrow<py::object>(o));")
        for n, t in zip(info.field_names, info.fields):
            tr = _strict(_trait(t))
            line = f"    {{ py::object v = pyb::getattr_fb(o, \"{n}\"); p->{n} = {tr}::in(v.ptr());"
            if _container(t):
                line += f" pyb::track<{tr}>(p->{n}, v.ptr());"
            out.append(line + " }")
        out.append(f"    cx->wb.push_back([o, p]() {{ pyc_back_{c}(o, p); }});")
        out.append("    return p;")
        out.append("}")
        out.append(f"static PyObject *pyc_new_{c}(const std::shared_ptr<::{c}> &p) {{")
        out.append("    pyb::ObjCtx *cx = pyb::objctx();")
        out.append(f"    PyObject *cls = pyc_bound[{idx[c]}];")
        out.append("    py::object o = pyb::steal(PyObject_CallMethod(cls, \"__new__\", \"O\", cls));")
        out.append(f"    cx->out[{key}] = o.ptr();")
        out.append("    cx->keep.push_back(o);")
        out.append(f"    pyc_back_{c}(o.ptr(), p);")
        out.append("    return o.inc_ref().ptr();")
        out.append("}")
    for c in names:
        if c not in ok:
            continue
        root = _root(cx, c)
        sub = [c] + cx.below(c)
        out.append(f"std::shared_ptr<::{c}> pyc_T_{c}::in(PyObject *o) {{")
        out.append("    if (o == Py_None) return nullptr;")
        out.append("    PyObject *t = reinterpret_cast<PyObject *>(Py_TYPE(o));")
        out.append("    if (" + " && ".join(f"t != pyc_bound[{idx[d]}]" for d in sub) + ")")
        out.append(f"        pyb::fallback(\"expected an instance of class {c} (a compiled class, not a Python subclass)\");")
        out.append("    pyb::ObjCtx *cx = pyb::objctx();")
        out.append("    auto it = cx->in.find(o);")
        out.append(f"    if (it != cx->in.end()) return std::static_pointer_cast<::{c}>("
                   f"std::static_pointer_cast<::{root}>(it->second));")
        for d in sub:
            out.append(f"    if (t == pyc_bound[{idx[d]}]) return pyc_in_{d}(o);")
        out.append("    return nullptr;")
        out.append("}")
        key = f"static_cast<const void *>(static_cast<::{root} *>(p.get()))"
        out.append(f"PyObject *pyc_T_{c}::out(const std::shared_ptr<::{c}> &p) {{")
        out.append("    if (!p) { Py_INCREF(Py_None); return Py_None; }")
        out.append("    pyb::ObjCtx *cx = pyb::objctx();")
        out.append(f"    auto it = cx->out.find({key});")
        out.append("    if (it != cx->out.end()) { Py_INCREF(it->second); return it->second; }")
        if c in cx.cid and cx.below(c):
            out.append("    switch (p->_cid) {")
            for d in cx.below(c):
                out.append(f"        case {cx.cid[d]}: return pyc_new_{d}(std::static_pointer_cast<::{d}>(p));")
            out.append("        default: break;")
            out.append("    }")
        out.append(f"    return pyc_new_{c}(p);")
        out.append("}")
    # class attributes: read from the Python class before a call, written back after it
    out.append("static void pyc_sync_in() {")
    for c in names:
        for attr, (t, _) in cx.cattr[c].items():
            tr = _trait(t)
            if tr is None:
                out.append(f"    pyb::fallback(\"class attribute {c}.{attr} cannot cross the Python boundary\");")
                continue
            tr = _strict(tr)
            line = f"    {{ py::object v = pyb::class_attr(pyc_bound[{idx[c]}], \"{attr}\"); ca_{c}_{attr}() = {tr}::in(v.ptr());"
            if _container(t):
                line += f" pyb::track<{tr}>(ca_{c}_{attr}(), v.ptr());"
            out.append(line + " }")
    out.append("}")
    out.append("static void pyc_sync_out() {")
    for c in names:
        for attr, (t, _) in cx.cattr[c].items():
            tr = _trait(t)
            if tr is not None:
                tr = _strict(tr)
                fn = "put_cont" if _container(t) else "put_field"
                out.append(f"    pyb::{fn}<{tr}>(pyc_bound[{idx[c]}], \"{attr}\", ca_{c}_{attr}());")
    out.append("}")
    out.append("")
    return out


def wrapper_prologue(tc, sig, owner) -> List[str]:
    """Lines right after the arena: binding check, object scope, class-attribute sync."""
    if not needs_objects(tc, sig, owner):
        return []
    return ["    pyc_need_bound();", "    pyb::ObjScope _objs;", "    pyc_sync_in();"]


def writeback_lines(tc, sig, owner) -> List[str]:
    if not needs_objects(tc, sig, owner):
        return []
    return ["_objs.writeback();", "pyc_sync_out();"]


def module_init(tc) -> List[str]:
    cx = getattr(tc, "cx", None)
    if cx is None or not cx.order:
        return []
    n = len(cx.order)
    return ['    m.def("_pythia_bind_classes", [](py::dict d) {',
            f'        for (int i = 0; i < {n}; ++i) {{',
            '            PyObject *c = PyDict_GetItemString(d.ptr(), pyc_bound_names[i]);',
            '            if (c && PyType_Check(c)) { Py_XDECREF(pyc_bound[i]); Py_INCREF(c); pyc_bound[i] = c; }',
            '        }',
            f'        for (int i = 0; i < {n}; ++i) if (!pyc_bound[i]) return false;',
            '        return true;',
            '    });']
